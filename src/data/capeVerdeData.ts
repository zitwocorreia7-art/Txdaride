/**
 * Validates and formats Cape Verde license plate
 * Valid pattern: 2 island letters (ST, SV, SL, BV, SA, FG, SN, BR, MA)
 * followed by '-' then 2 digits then '-' then 2 letters/digits (e.g. ST-23-AB or ST-45-78)
 */
export function formatCapeVerdePlate(input: string): string {
  const clean = input.toUpperCase().replace(/[^A-Z0-9]/g, '');
  if (clean.length <= 2) return clean;
  if (clean.length <= 4) return `${clean.slice(0, 2)}-${clean.slice(2)}`;
  return `${clean.slice(0, 2)}-${clean.slice(2, 4)}-${clean.slice(4, 6)}`;
}

export function isValidCapeVerdePlate(plate: string): boolean {
  const regex = /^(ST|SV|SL|BV|SA|FG|SN|BR|MA)-[0-9]{2}-[A-Z0-9]{2}$/;
  return regex.test(plate.trim().toUpperCase());
}

